/** Return a fresh, render-ready teaching strategy for a catalog lesson. */
export function getStrategy(lesson) {
  const spec = profiles[lesson.id];
  if (!spec) throw new RangeError(`No teaching strategy for lesson ${lesson.id}`);
  const result = {...spec, steps: spec.steps.map(step => {
    if (typeof step === 'number') return {...lesson.steps[step]};
    if (Array.isArray(step)) return {title: step[0], body: step[1]};
    return {title: step.title, body: step.refs.map(index => lesson.steps[index].body).join('')};
  })};
  if (spec.branches) result.branches = spec.branches.map(item => ({...item}));
  if (visuals[lesson.id]) result.visual = visuals[lesson.id];
  return result;
}
